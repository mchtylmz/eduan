const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
let panel = null;
const sandbox = {window: {}, document: {querySelector: () => panel}};
vm.runInNewContext(fs.readFileSync('public/backend/assets/study-panel.js', 'utf8'), sandbox);
const {eduanStudyStudentFormatter: student, eduanStudyNoteFormatter: note, eduanStudyEditFormatter: edit} = sandbox.window;
const payload = '<img src=x onerror="alert(1)">';
const identity = student(payload, {email: payload});
assert.doesNotMatch(identity, /<img/);
assert.equal((identity.match(/&lt;img/g) || []).length, 2);
assert.match(student('A', {email: 'a@example.test'}), /a@example.test/);
assert.doesNotMatch(note(payload), /<img/);
assert.match(note(payload), /&quot;alert/);
const long = note(payload.repeat(12));
assert.match(long, /<details/);
assert.doesNotMatch(long, /<img/);
assert.equal(edit(null, {id: 1, can_edit: false}), '—');
assert.equal(edit(null, {id: payload, can_edit: true}), '—');
panel = {dataset: {editLabel: payload}};
assert.match(edit(null, {id: 12, can_edit: true, table: 'study-notes'}), /data-study-edit-note="12"/);
assert.match(edit(null, {id: 13, can_edit: true, table: 'study-entries'}), /data-study-edit-entry="13"/);
assert.doesNotMatch(edit(null, {id: 12, can_edit: true}), /<img/);
console.log('Study panel formatters: 12 assertions passed');
